/**
 * Answer sheet OMR (optical mark recognition) layout constants.
 *
 * The OMR block is the fixed-geometry part of the answer sheet: it always has
 * exactly the same physical size and internal layout, no matter which test or
 * revision is printed. All positions are expressed in *design units* — an
 * arbitrary internal coordinate space of {@link OMR_DESIGN_WIDTH} ×
 * {@link OMR_DESIGN_HEIGHT} units that maps 1:1 to millimetres via
 * {@link OMR_UNITS_PER_MM} and is rendered through `FixedCanvas`.
 *
 * A scanner rectifies a photo/scan of the block by detecting the four ArUco
 * corner markers, computing a homography from their known positions, and
 * warping the block back to the canonical design-space rectangle. Every other
 * element (QR codes, future bubble grid) then sits at a known coordinate.
 *
 * This module is the single source of truth for that geometry — the print
 * renderer now and the scanner later must both use it.
 */

/**
 * Version of the answer-sheet layout, encoded in a QR code on every sheet.
 * Bump this whenever any constant in this file changes so future scanners can
 * tell which layout algorithm to apply.
 */
export const ANSWER_SHEET_FORMAT_VERSION = 1;

/** Physical width of the OMR block in millimetres (full usable A4 width). */
export const OMR_BLOCK_WIDTH_MM = 180;

/** Physical height of the OMR block in millimetres. */
export const OMR_BLOCK_HEIGHT_MM = 205;

/** Design units per millimetre — the internal resolution of the OMR block. */
export const OMR_UNITS_PER_MM = 10;

/** Internal design-space size of the OMR block (always the same). */
export const OMR_DESIGN_WIDTH = OMR_BLOCK_WIDTH_MM * OMR_UNITS_PER_MM;
export const OMR_DESIGN_HEIGHT = OMR_BLOCK_HEIGHT_MM * OMR_UNITS_PER_MM;

/**
 * ArUco dictionary the corner markers come from: the original ArUco
 * dictionary (5×5 data cells, ids 0–1023), generated by the `aruco-marker`
 * package. Detectable by OpenCV's DICT_ARUCO_ORIGINAL and by js-aruco.
 */
export const ARUCO_DICTIONARY_NAME = 'ARUCO_ORIGINAL';

/** Fixed ArUco ids reserved as unambiguous orientation anchors. */
export const ARUCO_TOP_LEFT_ANCHOR_ID = 0;
export const ARUCO_BOTTOM_RIGHT_ANCHOR_ID = 1023;

/** ArUco marker edge length in design units (80 = 8 mm, roughly text-line sized). */
export const ARUCO_MARKER_SIZE = 80;

/** Inset of each marker's outer edge from the block edges, in design units. */
export const ARUCO_MARKER_INSET = 50;

/** Extra reserved space around scanner fiducials, in design units. */
export const OMR_EXCLUSION_PADDING = 40;

export type OmrCorner = 'tl' | 'tr' | 'br' | 'bl';

export interface OmrRect {
	x: number;
	y: number;
	width: number;
	height: number;
}

export interface ArucoMarkerPlacement extends OmrRect {
	corner: OmrCorner;
	/** Marker id. TL and BR are fixed anchors; TR and BL carry small metadata. */
	id: number;
}

export interface OmrExclusionZone extends OmrRect {
	key: string;
	label: string;
}

/**
 * Top-left origins of the four corner markers, in design units.
 *
 * Marker ids use two fixed anchors and two metadata-bearing markers:
 * - TL = 0 (fixed anchor)
 * - TR = sheet format version, normalized away from reserved ids
 * - BR = 1023 (fixed anchor)
 * - BL = 10-bit checksum of the metadata QR payload, normalized away from reserved ids
 */
export function arucoMarkerPlacements(revisionId: string): ArucoMarkerPlacement[] {
	const farX = OMR_DESIGN_WIDTH - ARUCO_MARKER_INSET - ARUCO_MARKER_SIZE;
	const farY = OMR_DESIGN_HEIGHT - ARUCO_MARKER_INSET - ARUCO_MARKER_SIZE;
	const metadataPayload = sheetMetadataQrPayload(revisionId);
	const topRightId = metadataMarkerId(ANSWER_SHEET_FORMAT_VERSION);
	const bottomLeftId = metadataMarkerId(checksum10(metadataPayload), topRightId);
	return [
		markerPlacement('tl', ARUCO_TOP_LEFT_ANCHOR_ID, ARUCO_MARKER_INSET, ARUCO_MARKER_INSET),
		markerPlacement('tr', topRightId, farX, ARUCO_MARKER_INSET),
		markerPlacement('br', ARUCO_BOTTOM_RIGHT_ANCHOR_ID, farX, farY),
		markerPlacement('bl', bottomLeftId, ARUCO_MARKER_INSET, farY),
	];
}

function markerPlacement(
	corner: OmrCorner,
	id: number,
	x: number,
	y: number
): ArucoMarkerPlacement {
	return { corner, id, x, y, width: ARUCO_MARKER_SIZE, height: ARUCO_MARKER_SIZE };
}

/**
 * Map arbitrary 10-bit-ish metadata into marker ids that never collide with
 * fixed anchors nor the optional extra reserved id. Marker ids 1..1022 remain
 * available for metadata, while 0 and 1023 are hard anchors.
 */
export function metadataMarkerId(value: number, extraReservedId?: number): number {
	let id = (Math.abs(Math.trunc(value)) % (ARUCO_BOTTOM_RIGHT_ANCHOR_ID - 1)) + 1;
	if (id === extraReservedId) {
		id = id === ARUCO_BOTTOM_RIGHT_ANCHOR_ID - 1 ? 1 : id + 1;
	}
	return id;
}

/** QR code edge length in design units (180 = 18 mm). */
export const QR_CODE_SIZE = 180;

/** Gap between right-side fiducials and metadata QR, in design units. */
export const QR_METADATA_MARKER_GAP = 60;

/**
 * The full answer grid design plane. Future bubbles may use this whole area as
 * long as they avoid `omrExclusionZones(...)`.
 */
export const GRID_AREA = {
	x: 0,
	y: 0,
	width: OMR_DESIGN_WIDTH,
	height: OMR_DESIGN_HEIGHT,
} as const;

export function metadataQrPlacement(): OmrRect {
	return {
		x: OMR_DESIGN_WIDTH - ARUCO_MARKER_INSET - QR_CODE_SIZE,
		y:
			OMR_DESIGN_HEIGHT -
			ARUCO_MARKER_INSET -
			ARUCO_MARKER_SIZE -
			QR_METADATA_MARKER_GAP -
			QR_CODE_SIZE,
		width: QR_CODE_SIZE,
		height: QR_CODE_SIZE,
	};
}

/** Reserved areas future bubble/grid content must avoid. */
export function omrExclusionZones(revisionId: string): OmrExclusionZone[] {
	return [
		...arucoMarkerPlacements(revisionId).map((marker) =>
			exclusionZone(`aruco-${marker.corner}`, `ArUco ${marker.corner.toUpperCase()}`, marker)
		),
		exclusionZone('metadata-qr', 'QR metadanych', metadataQrPlacement()),
	];
}

function exclusionZone(key: string, label: string, rect: OmrRect): OmrExclusionZone {
	return {
		key,
		label,
		x: Math.max(0, rect.x - OMR_EXCLUSION_PADDING),
		y: Math.max(0, rect.y - OMR_EXCLUSION_PADDING),
		width:
			Math.min(OMR_DESIGN_WIDTH, rect.x + rect.width + OMR_EXCLUSION_PADDING) -
			Math.max(0, rect.x - OMR_EXCLUSION_PADDING),
		height:
			Math.min(OMR_DESIGN_HEIGHT, rect.y + rect.height + OMR_EXCLUSION_PADDING) -
			Math.max(0, rect.y - OMR_EXCLUSION_PADDING),
	};
}

/** Payload of the sheet metadata QR code. Keep keys short to keep the QR compact. */
export function sheetMetadataQrPayload(revisionId: string): string {
	return JSON.stringify({ r: revisionId, f: ANSWER_SHEET_FORMAT_VERSION });
}

/** 10-bit deterministic checksum for compact marker metadata. */
export function checksum10(value: string): number {
	let hash = 0x811c9dc5;
	for (let i = 0; i < value.length; i++) {
		hash ^= value.charCodeAt(i);
		hash = Math.imul(hash, 0x01000193);
	}
	return (hash >>> 0) & 0x3ff;
}

/** Convert design units to millimetres. */
export function omrUnitsToMm(units: number): number {
	return units / OMR_UNITS_PER_MM;
}
